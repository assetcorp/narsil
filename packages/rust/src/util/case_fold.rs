/// The Unicode full case folds of [Case Folding](algorithms.md#case-folding), keyed by the source code point.
struct FoldTable {
    single: HashMap<u32, u32>,
    multi: HashMap<u32, Vec<u32>>,
}

fn base_36(text: &str) -> Option<i64> {
    i64::from_str_radix(text, BASE_36).ok()
}

fn code_point(value: i64) -> Option<u32> {
    u32::try_from(value).ok()
}

fn single_folds() -> HashMap<u32, u32> {
    let mut table = HashMap::new();
    let mut source: i64 = 0;
    for entry in SINGLE_FOLDS.split(';').filter(|entry| !entry.is_empty()) {
        let mut parts = entry.split(',');
        let (Some(delta), Some(offset)) = (
            parts.next().and_then(base_36),
            parts.next().and_then(base_36),
        ) else {
            continue;
        };
        source += delta;
        if let (Some(from), Some(to)) = (code_point(source), code_point(source + offset)) {
            table.insert(from, to);
        }
    }
    table
}


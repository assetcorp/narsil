import type { SharedRouteOptions } from './options'
import type { RouteSpec } from './spec'

export function querySuggestionRoutes(shared: SharedRouteOptions): RouteSpec[] {
  const { named, namedBody } = shared
  return [
    {
      method: 'put',
      path: '/indexes/:name/query-suggestions',
      handler: 'updateQuerySuggestions',
      options: namedBody,
      operationId: 'updateQuerySuggestions',
      summary: 'Replace the popular query suggestions setting of an index',
      tags: ['QuerySuggestions'],
      request: 'QuerySuggestionsSetting',
      responses: { 200: 'OkResponse' },
    },
    {
      method: 'get',
      path: '/indexes/:name/query-suggestions',
      handler: 'querySuggestionsStatus',
      options: named,
      operationId: 'querySuggestionsStatus',
      summary: 'Report the setting, the last build, and the next build of popular query suggestions',
      tags: ['QuerySuggestions'],
      request: null,
      responses: { 200: 'QuerySuggestionsStatus' },
    },
    {
      method: 'post',
      path: '/indexes/:name/query-suggestions/record',
      handler: 'recordQuery',
      options: { ...namedBody, capturesContext: true },
      operationId: 'recordQuery',
      summary: 'Count a search that a person followed with a click, for the person that the server identifies',
      tags: ['QuerySuggestions'],
      request: 'RecordQueryBody',
      responses: { 200: 'RecordQueryResult' },
    },
    {
      method: 'post',
      path: '/indexes/:name/query-suggestions/build',
      handler: 'buildQuerySuggestions',
      options: named,
      operationId: 'buildQuerySuggestions',
      summary: 'Build the popular query suggestions of an index, as a task',
      tags: ['QuerySuggestions'],
      request: null,
      responses: { 202: 'TaskRecord' },
    },
    {
      method: 'get',
      path: '/indexes/:name/query-suggestions/preview',
      handler: 'previewQuerySuggestions',
      options: named,
      operationId: 'previewQuerySuggestions',
      summary: 'List the phrases that the next build would publish',
      tags: ['QuerySuggestions'],
      request: null,
      query: 'QuerySuggestionsPreviewQuery',
      responses: { 200: 'QuerySuggestionsPreview' },
    },
    {
      method: 'get',
      path: '/indexes/:name/query-suggestions/bans',
      handler: 'readQueryBans',
      options: named,
      operationId: 'readQueryBans',
      summary: 'Read the ban list of popular query suggestions',
      tags: ['QuerySuggestions'],
      request: null,
      responses: { 200: 'QueryBansBody' },
    },
    {
      method: 'put',
      path: '/indexes/:name/query-suggestions/bans',
      handler: 'replaceQueryBans',
      options: namedBody,
      operationId: 'replaceQueryBans',
      summary: 'Replace the ban list, and remove each newly banned phrase from every suggestions index',
      tags: ['QuerySuggestions'],
      request: 'QueryBansBody',
      responses: { 200: 'QueryBansBody' },
    },
    {
      method: 'post',
      path: '/indexes/:name/query-suggestions/remove',
      handler: 'removeQuery',
      options: namedBody,
      operationId: 'removeQuery',
      summary: 'Ban a phrase and remove it from every suggestions index of an index',
      tags: ['QuerySuggestions'],
      request: 'RemoveQueryBody',
      responses: { 200: 'RemoveQueryResponse' },
    },
    {
      method: 'post',
      path: '/indexes/:name/query-suggestions/manual',
      handler: 'addManualSuggestion',
      options: namedBody,
      operationId: 'addManualSuggestion',
      summary: 'Add a suggestion by hand, which a build leaves in place',
      tags: ['QuerySuggestions'],
      request: 'ManualQuerySuggestion',
      responses: { 200: 'ManualSuggestionResponse' },
    },
  ]
}

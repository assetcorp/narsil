import type { SharedRouteOptions } from './options'
import type { RouteSpec } from './spec'

export function indexRoutes(shared: SharedRouteOptions): RouteSpec[] {
  const { bare, named, namedBody, newIndexBody } = shared
  return [
    {
      method: 'post',
      path: '/indexes',
      handler: 'createIndex',
      options: newIndexBody,
      operationId: 'createIndex',
      summary: 'Create an index',
      tags: ['Indexes'],
      request: 'HttpCreateIndexBody',
      responses: { 201: 'IndexCreatedResponse' },
    },
    {
      method: 'get',
      path: '/indexes',
      handler: 'listIndexes',
      options: bare,
      operationId: 'listIndexes',
      summary: 'List every index',
      tags: ['Indexes'],
      request: null,
      responses: { 200: 'IndexListResponse' },
    },
    {
      method: 'del',
      path: '/indexes/:name',
      handler: 'dropIndex',
      options: named,
      operationId: 'dropIndex',
      summary: 'Drop an index',
      tags: ['Indexes'],
      request: null,
      responses: { 200: 'IndexDroppedResponse' },
    },
    {
      method: 'get',
      path: '/indexes/:name/stats',
      handler: 'indexStats',
      options: named,
      operationId: 'getStats',
      summary: 'Report the statistics of an index',
      tags: ['Indexes'],
      request: null,
      responses: { 200: 'IndexStats' },
    },
    {
      method: 'get',
      path: '/indexes/:name/partitions',
      handler: 'indexPartitions',
      options: named,
      operationId: 'getPartitionStats',
      summary: 'Report the statistics of each partition of an index',
      tags: ['Indexes'],
      request: null,
      responses: { 200: 'IndexPartitionsResponse' },
    },
    {
      method: 'get',
      path: '/indexes/:name/cluster',
      handler: 'clusterAllocation',
      options: named,
      operationId: 'getIndexAllocation',
      summary: 'Report how the cluster has placed the partitions of an index',
      tags: ['Cluster'],
      request: null,
      responses: { 200: 'ClusterAllocationResponse' },
    },
    {
      method: 'put',
      path: '/indexes/:name/replication-factor',
      handler: 'clusterReplicationFactor',
      options: namedBody,
      operationId: 'setReplicationFactor',
      summary: 'Change how many replicas each partition of an index keeps',
      tags: ['Cluster'],
      request: 'ReplicationFactorBody',
      responses: { 200: 'ReplicationFactorResponse' },
    },
    {
      method: 'post',
      path: '/indexes/:name/_clear',
      handler: 'clearIndex',
      options: named,
      operationId: 'clear',
      summary: 'Remove every document and keep the index',
      tags: ['Indexes'],
      request: null,
      responses: { 200: 'IndexClearedResponse' },
    },
    {
      method: 'post',
      path: '/indexes/:name/_open',
      handler: 'openIndex',
      options: named,
      operationId: 'open',
      summary: 'Load an index into memory',
      tags: ['Indexes'],
      request: null,
      responses: { 200: 'IndexStateResponse' },
    },
    {
      method: 'post',
      path: '/indexes/:name/_close',
      handler: 'closeIndex',
      options: named,
      operationId: 'close',
      summary: 'Release the memory of an index',
      tags: ['Indexes'],
      request: null,
      responses: { 200: 'IndexStateResponse' },
    },
    {
      method: 'get',
      path: '/indexes/:name/count',
      handler: 'count',
      options: named,
      operationId: 'countDocuments',
      summary: 'Count the documents in an index',
      tags: ['Indexes'],
      request: null,
      responses: { 200: 'DocumentCountResponse' },
    },
  ]
}

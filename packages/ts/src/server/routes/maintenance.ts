import { DOCUMENT_EXPORT_CONTENT_TYPE, SNAPSHOT_ARCHIVE_CONTENT_TYPE } from '../constants'
import type { SharedRouteOptions } from './options'
import type { RouteSpec } from './spec'

export function maintenanceRoutes(shared: SharedRouteOptions): RouteSpec[] {
  const { named, namedBody, spooledBody } = shared
  return [
    {
      method: 'post',
      path: '/indexes/:name/_checkpoint',
      handler: 'checkpoint',
      options: named,
      operationId: 'checkpoint',
      summary: 'Force a checkpoint of an index',
      tags: ['Maintenance'],
      request: null,
      responses: { 200: 'OkResponse' },
    },
    {
      method: 'post',
      path: '/indexes/:name/_rebuild-analysis',
      handler: 'rebuildAnalysis',
      options: named,
      operationId: 'rebuildAnalysis',
      summary: 'Reanalyse every document of an index, as a task',
      tags: ['Maintenance'],
      request: null,
      responses: { 202: 'TaskRecord' },
    },
    {
      method: 'post',
      path: '/indexes/:name/_change-analysis',
      handler: 'changeAnalysis',
      options: namedBody,
      operationId: 'changeAnalysis',
      summary: 'Change the language, stop words, or tokeniser of an index, as a task',
      tags: ['Maintenance'],
      request: { optional: 'ChangeAnalysisBody' },
      responses: { 202: 'TaskRecord' },
    },
    {
      method: 'get',
      path: '/indexes/:name/snapshot',
      handler: 'snapshot',
      options: named,
      operationId: 'snapshot',
      summary: 'Stream a snapshot archive of an index',
      tags: ['Maintenance'],
      request: null,
      responses: { 200: { contentType: SNAPSHOT_ARCHIVE_CONTENT_TYPE } },
    },
    {
      method: 'get',
      path: '/indexes/:name/vector-maintenance',
      handler: 'vectorMaintenance',
      options: named,
      operationId: 'vectorMaintenanceStatus',
      summary: 'Report the state of each vector field of an index',
      tags: ['Maintenance'],
      request: null,
      responses: { 200: 'VectorMaintenanceResponse' },
    },
    {
      method: 'post',
      path: '/indexes/:name/vectors/_compact',
      handler: 'compact',
      options: namedBody,
      operationId: 'compactVectors',
      summary: 'Compact the vector fields of an index',
      tags: ['Maintenance'],
      request: { optional: 'VectorFieldBody' },
      responses: { 200: 'OkResponse' },
    },
    {
      method: 'post',
      path: '/indexes/:name/vectors/_optimize',
      handler: 'optimize',
      options: namedBody,
      operationId: 'optimizeVectors',
      summary: 'Rebuild the vector graphs of an index, as a task',
      tags: ['Maintenance'],
      request: { optional: 'VectorFieldBody' },
      responses: { 202: 'TaskRecord' },
    },
    {
      method: 'post',
      path: '/indexes/:name/_rebalance',
      handler: 'rebalance',
      options: namedBody,
      operationId: 'rebalance',
      summary: 'Move an index to another partition count, as a task',
      tags: ['Maintenance'],
      request: 'RebalanceBody',
      responses: { 202: 'TaskRecord' },
    },
    {
      method: 'post',
      path: '/indexes/:name/partition-config',
      handler: 'partitionConfig',
      options: namedBody,
      operationId: 'updatePartitionConfig',
      summary: 'Change the partition settings of an index',
      tags: ['Maintenance'],
      request: { optional: 'PartitionConfig' },
      responses: { 200: 'OkResponse' },
    },
    {
      method: 'get',
      path: '/indexes/:name/synonyms',
      handler: 'readSynonyms',
      options: named,
      operationId: 'getSynonyms',
      summary: 'Read the synonym set of an index',
      tags: ['Maintenance'],
      request: null,
      responses: { 200: 'SynonymSetBody' },
    },
    {
      method: 'post',
      path: '/indexes/:name/synonyms',
      handler: 'replaceSynonyms',
      options: namedBody,
      operationId: 'updateSynonyms',
      summary: 'Replace the synonym set of an index',
      tags: ['Maintenance'],
      request: 'SynonymSetBody',
      responses: { 200: 'OkResponse' },
    },
    {
      method: 'post',
      path: '/indexes/:name/bm25',
      handler: 'updateBm25',
      options: namedBody,
      operationId: 'updateBM25',
      summary: 'Replace the BM25 setting of an index',
      tags: ['Maintenance'],
      request: 'BM25Params',
      responses: { 200: 'OkResponse' },
    },
    {
      method: 'post',
      path: '/indexes/:name/restore',
      handler: 'restore',
      options: spooledBody,
      operationId: 'restore',
      summary: 'Restore an index from a snapshot archive, as a task',
      tags: ['Maintenance'],
      request: { contentType: SNAPSHOT_ARCHIVE_CONTENT_TYPE },
      responses: { 202: 'TaskRecord' },
    },
    {
      method: 'get',
      path: '/indexes/:name/export',
      handler: 'exportDocuments',
      options: named,
      operationId: 'exportDocuments',
      summary: 'Stream a document export of an index',
      tags: ['Maintenance'],
      request: null,
      responses: { 200: { contentType: DOCUMENT_EXPORT_CONTENT_TYPE } },
    },
    {
      method: 'post',
      path: '/indexes/:name/import',
      handler: 'importExport',
      options: spooledBody,
      operationId: 'importDocumentExport',
      summary: 'Import a document export, as a task',
      tags: ['Maintenance'],
      request: { contentType: DOCUMENT_EXPORT_CONTENT_TYPE },
      responses: { 202: 'TaskRecord' },
    },
  ]
}

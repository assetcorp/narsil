import { DOCUMENT_EXPORT_CONTENT_TYPE } from '../constants'
import type { SharedRouteOptions } from './options'
import type { RouteSpec } from './spec'

export function documentRoutes(shared: SharedRouteOptions): RouteSpec[] {
  const { named, document, writeBody, readBody, batchBody, importBody, documentWriteBody } = shared
  return [
    {
      method: 'post',
      path: '/indexes/:name/documents',
      handler: 'insert',
      options: writeBody,
      operationId: 'insert',
      summary: 'Insert one document',
      tags: ['Documents'],
      request: 'InsertBody',
      responses: { 201: 'DocumentIdResponse' },
    },
    {
      method: 'post',
      path: '/indexes/:name/documents/_batch',
      handler: 'batch',
      options: batchBody,
      operationId: 'writeBatch',
      summary: 'Insert, update, or remove many documents, with a result for each',
      tags: ['Documents'],
      request: 'BatchBody',
      responses: { 200: 'BatchResponse' },
    },
    {
      method: 'post',
      path: '/indexes/:name/documents/_list',
      handler: 'list',
      options: readBody,
      operationId: 'listDocuments',
      summary: 'Read one page of stored documents',
      tags: ['Documents'],
      request: 'ListParams',
      responses: { 200: 'ListResult' },
      repeatable: true,
    },
    {
      method: 'post',
      path: '/indexes/:name/documents/_multi-get',
      handler: 'multiGet',
      options: readBody,
      operationId: 'getMultiple',
      summary: 'Fetch many documents by id',
      tags: ['Documents'],
      request: 'MultiGetBody',
      responses: { 200: 'MultiGetResponse' },
      repeatable: true,
    },
    {
      method: 'post',
      path: '/indexes/:name/documents/_import',
      handler: 'importNdjson',
      options: importBody,
      operationId: 'importNdjson',
      summary: 'Load newline-delimited documents, inside the request or as a task',
      tags: ['Documents'],
      request: { contentType: DOCUMENT_EXPORT_CONTENT_TYPE },
      query: 'ImportDocumentsQuery',
      responses: { 200: 'ImportResult', 202: 'TaskRecord' },
    },
    {
      method: 'post',
      path: '/indexes/:name/_wait-for-writes',
      handler: 'waitForWrites',
      options: named,
      operationId: 'waitForWrites',
      summary: 'Wait until every worker copy has applied the writes that returned before this request',
      tags: ['Documents'],
      request: null,
      responses: { 200: 'OkResponse' },
    },
    {
      method: 'get',
      path: '/indexes/:name/documents/:id',
      handler: 'get',
      options: document,
      operationId: 'get',
      summary: 'Read one document',
      tags: ['Documents'],
      request: null,
      responses: { 200: 'DocumentResponse' },
    },
    {
      method: 'get',
      path: '/indexes/:name/documents/:id/_exists',
      handler: 'exists',
      options: document,
      operationId: 'has',
      summary: 'Report whether an index holds a document with the id',
      tags: ['Documents'],
      request: null,
      responses: { 200: 'DocumentExistsResponse' },
    },
    {
      method: 'put',
      path: '/indexes/:name/documents/:id',
      handler: 'put',
      options: documentWriteBody,
      operationId: 'put',
      summary: 'Write one document under the id, whether or not the id exists',
      tags: ['Documents'],
      request: 'DocumentBody',
      responses: { 200: 'DocumentPutResponse', 201: 'DocumentPutResponse' },
    },
    {
      method: 'patch',
      path: '/indexes/:name/documents/:id',
      handler: 'patch',
      options: documentWriteBody,
      operationId: 'update',
      summary: 'Update one existing document',
      tags: ['Documents'],
      request: 'DocumentBody',
      responses: { 200: 'DocumentIdResponse' },
    },
    {
      method: 'del',
      path: '/indexes/:name/documents/:id',
      handler: 'remove',
      options: document,
      operationId: 'remove',
      summary: 'Remove one document',
      tags: ['Documents'],
      request: null,
      query: 'RemoveDocumentQuery',
      responses: { 200: 'DocumentRemovedResponse' },
    },
  ]
}

export function searchRoutes(shared: SharedRouteOptions): RouteSpec[] {
  const { readBody } = shared
  return [
    {
      method: 'post',
      path: '/indexes/:name/search',
      handler: 'search',
      options: readBody,
      operationId: 'query',
      summary: 'Search an index',
      tags: ['Search'],
      request: 'HttpQueryParams',
      responses: { 200: 'HttpQueryResult' },
      repeatable: true,
    },
    {
      method: 'post',
      path: '/indexes/:name/search/preflight',
      handler: 'preflight',
      options: readBody,
      operationId: 'preflight',
      summary: 'Count the documents that a search matches, with no hits',
      tags: ['Search'],
      request: 'HttpQueryParams',
      responses: { 200: 'PreflightResult' },
      repeatable: true,
    },
    {
      method: 'post',
      path: '/indexes/:name/suggest',
      handler: 'suggest',
      options: readBody,
      operationId: 'suggest',
      summary: 'Complete a prefix from the terms of an index',
      tags: ['Search'],
      request: 'SuggestParams',
      responses: { 200: 'SuggestResult' },
      repeatable: true,
    },
  ]
}

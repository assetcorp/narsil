package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const (
	modelsFile          = "generated_models.go"
	operationFilePrefix = "generated_operations_"
	generatedHeader     = "// Code generated by internal/generator from packages/ts/openapi.json. DO NOT EDIT.\n\n"
	defaultSpecPath     = "../ts/openapi.json"
	packageName         = "narsil"
	exitSpecFailure     = 2
	exitStaleCheckout   = 1
)

var importRules = []struct {
	path   string
	marker string
}{
	{"context", "ctx context.Context"},
	{"encoding/json", "json.Unmarshal("},
	{"io", "body io.Reader"},
	{"net/url", "url.Values{}"},
	{"strconv", "strconv.FormatBool("},
}

func renderFile(chunks []chunk) ([]byte, error) {
	var bodyText strings.Builder
	for _, piece := range chunks {
		bodyText.WriteString("\n")
		bodyText.WriteString(piece.text)
	}
	var imports []string
	for _, rule := range importRules {
		if strings.Contains(bodyText.String(), rule.marker) {
			imports = append(imports, quoteGo(rule.path))
		}
	}
	var source bytes.Buffer
	source.WriteString(generatedHeader)
	fmt.Fprintf(&source, "package %s\n", packageName)
	if len(imports) > 0 {
		fmt.Fprintf(&source, "\nimport (\n\t%s\n)\n", strings.Join(imports, "\n\t"))
	}
	source.WriteString(bodyText.String())
	formatted, err := format.Source(source.Bytes())
	if err != nil {
		return nil, fmt.Errorf("the generated Go does not parse: %w\n%s", err, source.String())
	}
	return formatted, nil
}

func generate(specPath string) (map[string][]byte, error) {
	data, err := os.ReadFile(specPath)
	if err != nil {
		return nil, err
	}
	document, err := decodeDocument(data)
	if err != nil {
		return nil, err
	}
	spec, err := buildAPI(document)
	if err != nil {
		return nil, err
	}
	return renderAll(spec)
}

func renderAll(spec *api) (files map[string][]byte, err error) {
	defer func() {
		if recovered := recover(); recovered != nil {
			failure, isSpec := recovered.(specError)
			if !isSpec {
				panic(recovered)
			}
			err = failure
		}
	}()
	p := newPlanner(spec)
	models := p.modelChunks()
	operations := p.operationChunks()
	unions, _ := p.unionChunks(0)
	files = map[string][]byte{}
	owners := map[string]string{}
	add := func(name, owner string, chunks []chunk) {
		if previous, clash := owners[name]; clash {
			failf("The tags %s and %s would both be written to %s", previous, owner, name)
		}
		owners[name] = owner
		rendered, renderErr := renderFile(chunks)
		if renderErr != nil {
			panic(specError{renderErr.Error()})
		}
		files[name] = rendered
	}
	add(modelsFile, "", append(models, unions...))
	tags := make([]string, 0, len(operations))
	for tag := range operations {
		tags = append(tags, tag)
	}
	sort.Strings(tags)
	for _, tag := range tags {
		add(operationFilePrefix+fileStem(tag)+".go", tag, operations[tag])
	}
	return files, nil
}

func existingFiles(directory string) (map[string][]byte, error) {
	matches, err := filepath.Glob(filepath.Join(directory, "*.go"))
	if err != nil {
		return nil, err
	}
	found := map[string][]byte{}
	for _, match := range matches {
		content, readErr := os.ReadFile(match)
		if readErr != nil {
			return nil, readErr
		}
		if bytes.HasPrefix(content, []byte(generatedHeader)) {
			found[filepath.Base(match)] = content
		}
	}
	return found, nil
}

func staleFiles(wanted, found map[string][]byte) []string {
	var stale []string
	for name, content := range wanted {
		if current, exists := found[name]; !exists || !bytes.Equal(current, content) {
			stale = append(stale, name)
		}
	}
	for name := range found {
		if _, kept := wanted[name]; !kept {
			stale = append(stale, name)
		}
	}
	sort.Strings(stale)
	return stale
}

func writeFiles(directory string, wanted, found map[string][]byte) error {
	for name := range found {
		if _, kept := wanted[name]; !kept {
			if err := os.Remove(filepath.Join(directory, name)); err != nil {
				return err
			}
		}
	}
	for name, content := range wanted {
		if current, exists := found[name]; exists && bytes.Equal(current, content) {
			continue
		}
		if err := os.WriteFile(filepath.Join(directory, name), content, 0o644); err != nil {
			return err
		}
	}
	return nil
}

func main() {
	write := flag.Bool("write", false, "write the generated files in place of checking them")
	specPath := flag.String("spec", defaultSpecPath, "the OpenAPI document to read")
	directory := flag.String("out", ".", "the package directory that holds the generated files")
	flag.Parse()
	wanted, err := generate(*specPath)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(exitSpecFailure)
	}
	found, err := existingFiles(*directory)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(exitSpecFailure)
	}
	if *write {
		if err := writeFiles(*directory, wanted, found); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(exitSpecFailure)
		}
		fmt.Printf("Wrote %d generated files\n", len(wanted))
		return
	}
	if stale := staleFiles(wanted, found); len(stale) > 0 {
		fmt.Fprintf(os.Stderr, "These generated files differ from %s, so regenerate them with -write:\n  %s\n",
			*specPath, strings.Join(stale, "\n  "))
		os.Exit(exitStaleCheckout)
	}
	fmt.Printf("All %d generated files match %s\n", len(wanted), *specPath)
}
